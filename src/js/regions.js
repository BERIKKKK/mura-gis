  /** Қазақша атау → ресми орысша атау (атаулы септік). Белгісіз атау (қолмен жазылған) өзгеріссіз қайтады. */
  function ru(name, region) {
    name = String(name || '').trim();
    if (!name) return name;
    if (RU_OBL[name]) return RU_OBL[name];
    if (RU_FULL[name]) return RU_FULL[name];
    var m = /^(.+) қаласы$/.exec(name);
    if (m && RU_CITY[m[1]]) return 'город ' + RU_CITY[m[1]];
    m = /^(.+) ауданы$/.exec(name);
    if (m) {
      if (region === 'Астана қаласы' && RU_ASTANA[m[1]]) return RU_ASTANA[m[1]];
      if (RU_DIST[m[1]]) return RU_DIST[m[1]];
    }
    return name;
  }
  /** Орысша атаудың септігі: kase — 'gen' (родительный: «Актюбинской области») не 'loc' (предложный: «Каргалинском районе»). */
  function ruCase(name, kase, region) {
    var s = ru(name, region), m;
    var loc = kase === 'loc';
    if ((m = /^(.*)ая область$/.exec(s))) return m[1] + 'ой области';
    if ((m = /^область (.+)$/.exec(s))) return 'области ' + m[1];
    if ((m = /^город (.+)$/.exec(s))) return (loc ? 'городе ' : 'города ') + m[1];
    if ((m = /^район (.+)$/.exec(s))) return (loc ? 'районе ' : 'района ') + m[1];
    if ((m = /^(.*)ний район$/.exec(s))) return m[1] + (loc ? 'нем районе' : 'него района');
    if ((m = /^(.*)ий район$/.exec(s))) return m[1] + (loc ? 'ом районе' : 'ого района');
    return s;
  }
