    /** Облыс атауы бойынша (қазақша не орысша). */
    fun find(name: String?): Region? {
        val n = name?.trim().orEmpty()
        if (n.isEmpty()) return null
        return list.firstOrNull { it.kk == n || it.ru.equals(n, ignoreCase = true) }
    }

    fun findUnit(region: Region?, name: String?): District? {
        val n = name?.trim().orEmpty()
        if (region == null || n.isEmpty()) return null
        return region.units.firstOrNull { it.kk == n || it.ru.equals(n, ignoreCase = true) }
    }

