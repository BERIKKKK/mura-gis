    data class District(val kk: String, val ru: String, val noteKk: String = "", val noteRu: String = "") {
        val name: Localized get() = Localized(kk, ru)
        fun label(lang: Lang): String = (if (lang == Lang.RU) ru else kk) + if (noteKk.isEmpty()) "" else " (" + (if (lang == Lang.RU) noteRu else noteKk) + ")"
    }

    /** Облыс не республикалық маңызы бар қала ([city]). */
    data class Region(val kk: String, val ru: String, val city: Boolean, val units: List<District>) {
        val name: Localized get() = Localized(kk, ru)
        fun label(lang: Lang): String = if (lang == Lang.RU) ru else kk
    }

